class Macros:
    def __init__(self):
        self.d: dict[str, str] = {}

    def __setitem__(self, name, value):
        assert re.fullmatch(r"[A-Za-z]+", name), name
        self.d[name] = value

    def write(self, path):
        lines = ["% GENERATED by `python -m mbca study paper` -- do not edit"]
        lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.d.items())]
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def f2(x, signed=False):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "n/a"
    return f"{x:+.2f}" if signed else f"{x:.2f}"


def pct(x, signed=False):
    return f"{100 * x:+.1f}\\%" if signed else f"{100 * x:.1f}\\%"


def esc(s):
    return str(s).replace("_", "\\_").replace("%", "\\%").replace("&", "\\&").replace("^", "\\^{}")


def longtable(path, caption, label, header, rows, align):
    out = [f"\\begin{{longtable}}{{{align}}}",
           f"\\caption{{{caption}}} \\label{{{label}}} \\\\", "\\toprule", " & ".join(header) + " \\\\",
           "\\midrule", "\\endhead", "\\bottomrule", "\\endfoot"]
    out += [" & ".join(map(str, r)) + " \\\\" for r in rows]
    out.append("\\end{longtable}")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


