S1_KIND = {"ML Regime Filter": "independent", "ML Meta-Labeling": "narrowing", "ML Position Sizing": "narrowing",
           "ML Entry": "replacing", "ML Exit": "replacing", "Combinations": "combination"}


def study1(M: Macros) -> None:
    from .report import forest_plot, matrix_plot

    p = pd.read_csv(S1 / "paper" / "component_attribution_table.csv")
    rep = pd.read_csv(S1 / "replication" / "attribution_table.csv")
    cmp_ = pd.read_csv(S1 / "replication" / "paper_vs_replication.csv")
    M["SoneConfigs"] = str(len(p))
    M["SoneSigGain"] = str(int((p.significant & (p.delta_sharpe > 0)).sum()))
    M["SoneSigLoss"] = str(int((p.significant & (p.delta_sharpe < 0)).sum()))
    ex = p[p.component == "ML Exit"]
    M["SoneExitSigLoss"] = str(int((ex.significant & (ex.delta_sharpe < 0)).sum()))
    M["SoneExitConfigs"] = str(len(ex))
    # trade-count inflation of ML Exit vs its campaign baseline (paper CSV)
    e = pd.read_csv(S1 / "paper" / "ml_exit_all.csv")
    r = (e[e.variant == "ml_exit"].set_index(["market", "window"])["n_trades"]
         / e[e.variant == "baseline"].set_index(["market", "window"])["n_trades"]).dropna()
    M["SoneExitInflLo"], M["SoneExitInflHi"] = f"{r.min():.1f}", f"{r.max():.1f}"
    bc = p[(p.component == "Combinations") & p.variant.str.startswith("Best") & (p.market == "indian_equities")]
    for w, tag in (("holdout", "Hold"), ("forward", "Fwd")):
        row = bc[bc.window == w].iloc[0]
        M[f"SoneBest{tag}Base"], M[f"SoneBest{tag}Var"] = f2(row.baseline_sharpe), f2(row.variant_sharpe)
        M[f"SoneBest{tag}CiLo"], M[f"SoneBest{tag}CiHi"] = f"{row.bootstrap_ci_lo:.3f}", f"{row.bootstrap_ci_hi:.3f}"
        M[f"SoneBest{tag}CiLoAnn"] = f"{row.bootstrap_ci_lo * np.sqrt(252):.1f}"
        M[f"SoneBest{tag}CiHiAnn"] = f"{row.bootstrap_ci_hi * np.sqrt(252):.1f}"
    fxb = p[(p.market == "forex_4pair") & (p.window == "holdout")].baseline_sharpe.iloc[0]
    M["SoneForexBase"] = f2(fxb)
    fx = p[p.market == "forex_4pair"]
    M["SoneForexSigLoss"], M["SoneForexConfigs"] = str(int((fx.significant & (fx.delta_sharpe < 0)).sum())), str(len(fx))
    # replication
    M["SoneRepSigGain"] = str(int((rep.significant & (rep.delta_sharpe > 0) & (rep.kind != "control")).sum()))
    M["SoneRepSigLoss"] = str(int((rep.significant & (rep.delta_sharpe < 0)).sum()))
    M["SoneRepSignAgree"] = str(int(cmp_.sign_agrees.sum()))
    fxr = cmp_[cmp_.market == "forex"]
    M["SoneRepForexSigLoss"] = str(int((fxr.significant_rep & (fxr.delta_sharpe_rep < 0)).sum()))
    ml = rep[rep.variant == "ML Exit"].set_index(["market", "window"])["n_trades"]
    bl = rep[rep.variant == "Baseline (rule-based)"].set_index(["market", "window"])["n_trades"]
    rr = (ml / bl).dropna()
    M["SoneRepExitInflLo"], M["SoneRepExitInflHi"] = f"{rr.min():.1f}", f"{rr.max():.1f}"
    b = cmp_[(cmp_.market == "indian_equities") & cmp_.variant.str.startswith("Best")].set_index("window")
    M["SoneRepBestHold"], M["SoneRepBestFwd"] = f2(b.loc["holdout", "delta_sharpe_rep"], True), f2(
        b.loc["forward", "delta_sharpe_rep"], True)
    M["SoneBestHoldDelta"], M["SoneBestFwdDelta"] = f2(b.loc["holdout", "delta_sharpe_paper"], True), f2(
        b.loc["forward", "delta_sharpe_paper"], True)
    rb = rep[(rep.variant == "Baseline (rule-based)")].set_index(["market", "window"])["sharpe"]
    M["SoneRepForexBase"] = f2(rb.loc[("forex", "holdout")])
    M["SoneRepIndiaBase"] = f2(rb.loc[("indian_equities", "holdout")])
    mf = cmp_[(cmp_.market == "forex") & (cmp_.variant == "ML Meta-Labeling")].iloc[0]
    M["SoneMetaForexPaper"], M["SoneMetaForexRep"] = f2(mf.delta_sharpe_paper, True), f2(mf.delta_sharpe_rep, True)

    # tables
    rows = [[esc(r.component), esc(r.variant), esc(r.market), r.window, f2(r.baseline_sharpe), f2(r.variant_sharpe),
             f2(r.delta_sharpe, True), f"[{r.bootstrap_ci_lo:.3f}, {r.bootstrap_ci_hi:.3f}]",
             "\\textbf{yes}" if r.significant else "no"] for r in p.itertuples()]
    longtable(TEX / "s1_attribution.tex", "Study 1: all 60 configurations (original study results). CI = unpaired "
              "i.i.d.\\ bootstrap of the per-day Sharpe difference.", "tab:s1", ["Component", "Variant", "Market",
              "Window", "Base", "Variant", "$\\Delta$SR", "95\\% CI (per day)", "Sig."], rows, "l l l l r r r l l")
    rows = [[esc(r.market), r.window, esc(r.variant), f2(r.delta_sharpe_paper, True), f2(r.delta_sharpe_rep, True),
             "sig." if r.significant_paper else "n.s.", "sig." if r.significant_rep else "n.s."] for r in cmp_.itertuples()]
    longtable(TEX / "s1_replication.tex", "Study 1: original results vs.\\ independent re-implementation "
              "(annualized $\\Delta$Sharpe).", "tab:s1rep", ["Market", "Window", "Variant", "Original", "Replication",
              "Orig.", "Repl."], rows, "l l l r r l l")
    # figures (unit-corrected)
    t = p.rename(columns={"variant_sharpe": "sharpe", "bootstrap_ci_lo": "ci_lo", "bootstrap_ci_hi": "ci_hi"})
    t["kind"] = t["component"].map(S1_KIND)
    t["variant"] = [v if c in ("ML Regime Filter", "Combinations") else c for c, v in zip(t.component, t.variant)]
    forest_plot(t, FIG / "s1_forest.png", "Study 1: delta Sharpe vs rule-based baseline")
    matrix_plot(t, FIG / "s1_matrix.png", "Study 1: ML Opportunity Matrix")


